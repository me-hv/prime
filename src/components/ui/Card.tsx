import * as React from "react";
import { cn } from "@/lib/utils";

const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement> & { hoverEffect?: boolean; glow?: boolean }
>(({ className, hoverEffect, glow, ...props }, ref) => (
  <div
    ref={ref}
    className={cn(
      "rounded-xl border border-prime-borderSubtle bg-prime-card/90 text-prime-text shadow-prime-sm transition-all duration-200",
      hoverEffect && "hover:border-prime-border hover:bg-prime-card hover:shadow-prime-md",
      glow && "ring-1 ring-prime-gold/20 shadow-prime-glow-gold",
      className
    )}
    {...props}
  />
));
Card.displayName = "Card";

